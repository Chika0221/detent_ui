"""Resolve the canonical DTCG tokens and link Flutter widgets to .pen nodes.
Run from the package root. No third-party Python dependencies required.
"""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = json.loads((root / 'design_tokens.json').read_text())
flat = {}
def flatten(obj, prefix=''):
    for key, value in obj.items():
        if key.startswith('$'): continue
        path = f'{prefix}.{key}' if prefix else key
        if isinstance(value, dict) and '$value' in value: flat[path] = value
        elif isinstance(value, dict): flatten(value, path)
flatten(source)
def resolve(key, stack=()):
    if key in stack: raise ValueError(f'Circular reference: {stack + (key,)}')
    value = flat[key]['$value']
    if isinstance(value, str) and value.startswith('{') and value.endswith('}'):
        return resolve(value[1:-1], stack + (key,))
    return value
lines = ['// ignore_for_file: constant_identifier_names', '// Generated by tool/generate_tokens.py from design_tokens.json.', "import 'package:flutter/painting.dart';", '', 'abstract final class NuiTokens {']
for key, token in flat.items():
    value = resolve(key)
    name = key.replace('.', '_').replace('-', '_')
    typ = token.get('$type')
    if isinstance(value, dict) and value.get('colorSpace') == 'srgb':
        r,g,b = [round(v*255) for v in value['components']]
        a = round(value.get('alpha',1)*255)
        lines.append(f'  static const {name} = Color(0x{a:02X}{r:02X}{g:02X}{b:02X});')
    elif isinstance(value, dict) and 'unit' in value:
        lines.append(f"  static const double {name} = {float(value['value'])};")
    elif isinstance(value, (float,int)):
        lines.append(f'  static const double {name} = {float(value)};')
    elif isinstance(value, list):
        lines.append(f'  static const {name} = <double>{json.dumps([float(x) for x in value])};')
    elif isinstance(value, str):
        lines.append(f'  static const {name} = {json.dumps(value)};')
lines.append('}')
(root / 'lib/src/foundation/tokens.g.dart').write_text('\n'.join(lines)+'\n')
pen = json.loads((root / 'ui_design.pen').read_text())
nodes = {}
def walk(obj):
    if isinstance(obj, dict):
        if 'id' in obj: nodes[obj['id']] = obj
        for v in obj.values(): walk(v)
    elif isinstance(obj, list):
        for v in obj: walk(v)
walk(pen)
registry = json.loads((root / 'component_registry.json').read_text())
for item in registry['reviewSets']:
    assert item['nodeId'] in nodes, item
print(f'Resolved {len(flat)} tokens; validated {len(registry["reviewSets"])} .pen component links.')
